"""
PostgreSQL backend for the RLS experiments (research only; the app runs on SQLite).

Builds the same 10-table schema and seed data in Postgres and adds:
- ``app_reader``: a NOLOGIN, SELECT-only role; queries run as it via SET LOCAL ROLE.
- Row-Level Security on every table (FORCE), keyed on the session setting
  ``app.tenant_id`` (``tenants`` is keyed on ``id``).
- ``iso_<t>`` schemas holding only tenant t's rows, for the differential
  isolation oracle (same role as tenant_only_connection() on SQLite).

Requires the container in docker-compose.research.yml (or PG_DSN).
"""

from __future__ import annotations

import os
import re
from decimal import Decimal
from typing import Any

import psycopg

from app.database import _SEED_SQL, TABLE_COLUMNS, TABLE_DDLS, TENANT_SCOPED_TABLES, unique_columns

PG_DSN = os.getenv(
    "PG_DSN",
    f"postgresql://postgres:{os.getenv('RESEARCH_PG_PASSWORD', 'research')}@127.0.0.1:55432/guardcache",
)
TENANT_IDS = (1, 2)
_SCHEMAS = {"public", *(f"iso_{t}" for t in TENANT_IDS)}

_conn: psycopg.Connection | None = None


def _pg_ddl(ddl: str) -> str:
    """Translate the SQLite DDL used by the app into Postgres DDL."""
    ddl = ddl.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    ddl = ddl.replace("(datetime('now'))", "(to_char(now(), 'YYYY-MM-DD HH24:MI:SS'))")
    return re.sub(r"\bREAL\b", "DOUBLE PRECISION", ddl)


def available() -> bool:
    try:
        with psycopg.connect(PG_DSN, connect_timeout=2):
            return True
    except psycopg.Error:
        return False


def setup(extra_sql: str = "") -> None:
    """(Re)create schema, seed data, RLS policies, reader role and iso schemas."""
    global _conn
    with psycopg.connect(PG_DSN, autocommit=True) as conn:
        for schema in _SCHEMAS:
            conn.execute(f"DROP SCHEMA IF EXISTS {schema} CASCADE")
        conn.execute("CREATE SCHEMA public")
        for ddl in TABLE_DDLS.values():
            conn.execute(_pg_ddl(ddl))
        conn.execute(_SEED_SQL)
        if extra_sql:
            conn.execute(extra_sql)

        conn.execute("DO $$ BEGIN CREATE ROLE app_reader NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$")
        conn.execute("GRANT USAGE ON SCHEMA public TO app_reader")
        conn.execute("GRANT SELECT ON ALL TABLES IN SCHEMA public TO app_reader")
        for table in TABLE_COLUMNS:
            key = "tenant_id" if table in TENANT_SCOPED_TABLES else "id"
            conn.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
            conn.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
            conn.execute(
                f"CREATE POLICY tenant_isolation ON {table} FOR SELECT TO app_reader "
                f"USING ({key} = current_setting('app.tenant_id', true)::int)"
            )

        for t in TENANT_IDS:
            conn.execute(f"CREATE SCHEMA iso_{t}")
            for table in TABLE_COLUMNS:
                key = "tenant_id" if table in TENANT_SCOPED_TABLES else "id"
                conn.execute(
                    f"CREATE TABLE iso_{t}.{table} AS SELECT * FROM public.{table} WHERE {key} = {t}"
                )
    if _conn is not None:
        _conn.close()
        _conn = None


def _connection() -> psycopg.Connection:
    global _conn
    if _conn is None or _conn.closed:
        _conn = psycopg.connect(PG_DSN)
        _conn.read_only = True
    return _conn


def _plain(v: Any) -> Any:
    return float(v) if isinstance(v, Decimal) else v


def execute(
    sql: str, *, schema: str = "public", rls_tenant: int | None = None, timeout_ms: int = 5000
) -> list[dict[str, Any]]:
    """
    Run one read-only statement and roll back.

    ``rls_tenant`` runs it as ``app_reader`` with ``app.tenant_id`` set, so RLS
    applies; otherwise it runs as the owner (no RLS) against *schema*.
    """
    if schema not in _SCHEMAS:
        raise ValueError(f"unknown schema {schema!r}")
    conn = _connection()
    try:
        with conn.cursor() as cur:
            cur.execute(f"SET LOCAL statement_timeout = {int(timeout_ms)}")
            cur.execute(f"SET LOCAL search_path TO {schema}")
            if rls_tenant is not None:
                cur.execute("SET LOCAL ROLE app_reader")
                cur.execute("SELECT set_config('app.tenant_id', %s, true)", (str(int(rls_tenant)),))
            cur.execute(sql)
            cols = unique_columns([d.name for d in cur.description] if cur.description else [])
            return [dict(zip(cols, map(_plain, row))) for row in cur.fetchall()]
    finally:
        conn.rollback()
